// Local development server: `npm run dev`. Serves dist/ (like any static server) and lets the dev panel's interior editor save a house's furniture back into the code.
//   POST /__dev/save-interior  {prop, layout: {items: [[piece, ...], ...]}}  ->  rewrites dist/interior-layouts.js (and the same file in the release dist/index.html points at, so a reload shows it).
// It is for your own computer only: it listens on 127.0.0.1, refuses any other Host header (DNS rebinding) and any request without the dev header, accepts nothing but that one write, and
// re-checks every piece with the game's own cleanItem(), so the file it writes is always a layout the game accepts.
import {createServer} from 'node:http';
import {readFile,writeFile,access} from 'node:fs/promises';
import {join,extname,resolve,sep} from 'node:path';
import {pathToFileURL} from 'node:url';

const TYPES={'.html':'text/html; charset=utf-8','.js':'text/javascript; charset=utf-8','.css':'text/css; charset=utf-8','.jpg':'image/jpeg','.png':'image/png','.json':'application/json','.svg':'image/svg+xml'};
const HEADER=`// Saved house interiors: furniture layouts written by the dev panel's interior editor (Dev Mode > Interior editor > Save to code, through \`npm run dev\`; scripts/dev-server.mjs).
// One entry per house model: {items: [ground floor pieces, upper floor pieces]}, a piece is {id, x, z, yaw, y} in room metres (the room's middle is 0, 0; +z is the door side).
// A house with no entry here gets the layout generated by houseLayout() in interiors.js. The stairs always come from the generator. You can edit this file by hand.
`;
export function serialize(layouts){
 const out=[HEADER+'export const INTERIOR_LAYOUTS={'];
 for(const prop of Object.keys(layouts).sort()){
  out.push(` ${JSON.stringify(prop)}:{items:[`);
  layouts[prop].items.forEach((list,floor)=>{out.push(`  [ // floor ${floor}`);for(const item of list)out.push(`   ${JSON.stringify(item)},`);out.push('  ],')});
  out.push(' ]},');
 }
 out.push('};','');return out.join('\n');
}

export function createDevServer({root='dist',port=8000,host='127.0.0.1'}={}){
 root=resolve(root);
 let actualPort=port;
 const send=(res,status,body,type='text/plain; charset=utf-8')=>{res.writeHead(status,{'content-type':type,'cache-control':'no-store'});res.end(body)};
 const hostOk=header=>{const h=(header||'').toLowerCase();return [`localhost:${actualPort}`,`127.0.0.1:${actualPort}`,`[::1]:${actualPort}`].includes(h)};

 async function save(body){
  let data;try{data=JSON.parse(body)}catch{return {status:400,error:'That is not JSON.'}}
  const {FLOORS,cleanItem,LOCKED}=await import(pathToFileURL(join(root,'interiors.js')).href+'?v='+Date.now());
  const prop=data?.prop,floors=FLOORS[prop];
  if(typeof prop!=='string'||floors===undefined)return {status:400,error:'Unknown house model.'};
  if(!Array.isArray(data.layout?.items)||data.layout.items.length!==floors)return {status:400,error:`${prop} has ${floors} floor(s).`};
  const items=[];
  for(const list of data.layout.items){
   if(!Array.isArray(list)||list.length>120)return {status:400,error:'Too many pieces, or not a list.'};
   const clean=[];for(const raw of list){if(raw&&LOCKED.has(raw.id))continue;const item=cleanItem(raw);if(!item)return {status:400,error:'A piece is not valid furniture: '+JSON.stringify(raw).slice(0,120)};clean.push(item)}
   items.push(clean);
  }
  const file=join(root,'interior-layouts.js');
  let current={};try{current={...(await import(pathToFileURL(file).href+'?v='+Date.now())).INTERIOR_LAYOUTS}}catch{}
  current[prop]={items};
  const text=serialize(current),written=[file];
  await writeFile(file,text);
  // the packaged release the page loads: the same file, so a reload shows what you saved
  try{const html=await readFile(join(root,'index.html'),'utf8'),release=html.match(/releases\/([^/'"]+)\/game\.js/)?.[1];
   if(release){const copy=join(root,'releases',release,'interior-layouts.js');await access(join(root,'releases',release));await writeFile(copy,text);written.push(copy)}}catch{}
  return {status:200,ok:true,prop,pieces:items.flat().length,files:written.map(f=>f.slice(root.length+1).split(sep).join('/'))};
 }

 const server=createServer(async(req,res)=>{
  try{
   if(!hostOk(req.headers.host))return send(res,403,'Unknown host.');
   const url=new URL(req.url,'http://x');
   if(req.method==='POST'&&url.pathname==='/__dev/save-interior'){
    if(req.headers['x-city-dev']!=='1')return send(res,403,'Missing dev header.');
    const origin=req.headers.origin;if(origin&&!hostOk(origin.replace(/^https?:\/\//,'')))return send(res,403,'Cross-origin request refused.');
    if(!/^application\/json/i.test(req.headers['content-type']||''))return send(res,415,'Send JSON.');
    const chunks=[];let size=0;for await(const chunk of req){size+=chunk.length;if(size>200_000)return send(res,413,'Too large.');chunks.push(chunk)}
    const result=await save(Buffer.concat(chunks).toString('utf8'));
    return send(res,result.status,JSON.stringify(result.error?{ok:false,error:result.error}:result),'application/json');
   }
   if(req.method!=='GET'&&req.method!=='HEAD')return send(res,405,'Not allowed.');
   const path=decodeURIComponent(url.pathname),file=resolve(root,'.'+(path==='/'?'/index.html':path));
   if(file!==root&&!file.startsWith(root+sep))return send(res,403,'Outside the site.');
   let body;try{body=await readFile(file)}catch{return send(res,404,'Not found.')}
   res.writeHead(200,{'content-type':TYPES[extname(file)]||'application/octet-stream','cache-control':'no-store'});res.end(req.method==='HEAD'?undefined:body);
  }catch(error){send(res,500,'Server error: '+error.message)}
 });
 return {server,listen:()=>new Promise((ok,fail)=>{server.once('error',fail);server.listen(port,host,()=>{actualPort=server.address().port;ok(actualPort)})}),close:()=>new Promise(r=>server.close(r))};
}

if(process.argv[1]&&import.meta.url===pathToFileURL(process.argv[1]).href){
 const dev=createDevServer({port:Number(process.env.PORT)||8000});
 dev.listen().then(port=>{console.log(`City Life dev server: http://localhost:${port}\nThe dev panel's interior editor saves into dist/interior-layouts.js (and the current release). Ctrl+C to stop.`)},error=>{console.error(error.code==='EADDRINUSE'?'That port is in use. Stop the other server, or run: PORT=8001 npm run dev (PowerShell: $env:PORT=8001; npm run dev)':error.message);process.exitCode=1});
}
